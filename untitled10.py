def generate_realistic_iocs(sample_row):
    """Generate realistic IoCs for a malware sample"""

    family = sample_row['family']
    sample_id = sample_row['sample_id']

    # Generate file hashes
    random_bytes = f"{sample_id}_{family}_{datetime.now()}".encode()
    md5_hash = hashlib.md5(random_bytes).hexdigest()
    sha256_hash = hashlib.sha256(random_bytes).hexdigest()

    # Generate C2 domains based on family
    domain_patterns = {
        'Ransomware': ['pay', 'decrypt', 'unlock', 'restore'],
        'Banking Trojan': ['secure', 'bank', 'login', 'verify'],
        'Information Stealer': ['update', 'sync', 'cdn', 'api'],
        'Backdoor': ['service', 'host', 'remote', 'access'],
        'Rootkit': ['system', 'driver', 'kernel', 'boot']
    }

    pattern = random.choice(domain_patterns.get(family, ['malware']))
    tld = random.choice(['com', 'net', 'org', 'info', 'xyz'])
    domain = f"{pattern}{random.randint(100, 999)}.{tld}"

    # Generate IP address (realistic ranges)
    ip_ranges = ['192.168', '10.0', '172.16', '185.220', '198.51']
    ip_base = random.choice(ip_ranges)
    ip = f"{ip_base}.{random.randint(1, 254)}.{random.randint(1, 254)}"

    # Generate registry key
    reg_keys = [
        'HKLM\\Software\\Microsoft\\Windows\\CurrentVersion\\Run',
        'HKLM\\Software\\Microsoft\\Windows\\CurrentVersion\\RunOnce',
        'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run',
        'HKLM\\System\\CurrentControlSet\\Services'
    ]
    reg_key = f"{random.choice(reg_keys)}\\{family.replace(' ', '')}"

    # Generate file path
    paths = ['%APPDATA%', '%TEMP%', '%PROGRAMDATA%', 'C:\\Windows\\System32']
    filename = f"{family.lower().replace(' ', '_')}_{random.randint(1000, 9999)}.exe"
    file_path = f"{random.choice(paths)}\\{filename}"

    # Generate mutex
    mutex = f"Global\\{family.replace(' ', '')}_Mutex_{random.randint(1000, 9999)}"

    # Network port
    ports = [80, 443, 8080, 8443, 1080, 3389]
    port = random.choice(ports)

    return {
        'Sample_ID': sample_id,
        'Family': family,
        'MD5': md5_hash,
        'SHA256': sha256_hash,
        'C2_Domain': domain,
        'C2_IP': ip,
        'C2_Port': port,
        'Registry_Key': reg_key,
        'File_Path': file_path,
        'Mutex': mutex,
        'Confidence': random.choice(['High', 'High', 'High', 'Medium'])
    }

